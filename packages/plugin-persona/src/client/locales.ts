/**
 * Locale dictionaries for the persona browser half (namespace
 * 'tentacle-persona'). Both built-in locales ship together — the locale
 * runtime enforces bilingual balance at registration, so the two dictionaries
 * must stay key-identical.
 */
export type Translate = (key: PersonaLocaleKey) => string

/** Interpolate `{name}`-style placeholders in one localized template. */
export function fmt(template: string, params: Readonly<Record<string, string>>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) => params[key] ?? match)
}

