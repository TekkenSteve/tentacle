const STYLE_ID = 'tentacle-data-console-style'

/** Inject the few rules inline styles cannot express (dialog width, scrollbars). */
export function ensureConsoleStyles(): void {
  if (typeof document === 'undefined' || document.getElementById(STYLE_ID) !== null) return
  const style = document.createElement('style')
  style.id = STYLE_ID
  style.textContent = [
    '.tentacle-data-dialog{width:min(640px,100%);}',
    '.tentacle-data-content{max-height:calc(100vh - 150px);overflow-y:auto;}',
    '.tentacle-data-board::-webkit-scrollbar,.tentacle-data-thread-cards::-webkit-scrollbar,.tentacle-data-side::-webkit-scrollbar{width:6px;height:6px;}',
    '.tentacle-data-board::-webkit-scrollbar-thumb,.tentacle-data-thread-cards::-webkit-scrollbar-thumb,.tentacle-data-side::-webkit-scrollbar-thumb{background:var(--dsw-alias-border-l3);border-radius:999px;}',
  ].join('\n')
  document.head.appendChild(style)
}
