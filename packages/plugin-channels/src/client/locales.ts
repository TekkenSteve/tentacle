/** True when this dictionary can resolve `key`. */
export function hasLocaleKey(key: string): key is ChannelsLocaleKey {
  return Object.prototype.hasOwnProperty.call(zh, key)
}

/**
 * Resolve a host-declared locale key, falling back to a readable value when the
 * dictionary does not know it (a host schema may add a field before the client
 * ships its copy).
 */
export function localize(t: Translate, key: string | undefined, fallback: string): string {
  if (key === undefined) return fallback
  return hasLocaleKey(key) ? t(key) : fallback
}

/** Minimal `{placeholder}` interpolation for the stats/confirm/probe lines. */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(vars[key] ?? `{${key}}`))
}

